/** PRODUCT-04: no source, pointers, snippets or field names in the default report.
 * This pure module has no browser APIs, requests, storage, or side effects.
 */
export const REPORT_FORMAT_VERSION = 'jsonparseweb.report.v1';
const MAX_FINDINGS = 100;
const MAX_DRIFT = 100;
const slice = (value, max) => typeof value === 'string' ? value.slice(0, max) : '';
const count = value => Number.isSafeInteger(value) && value >= 0 ? value : 0;
const knownSeverity = value => ['warning', 'info', 'error'].includes(value) ? value : 'info';
const rule = value => typeof value === 'string' && /^[A-Z][A-Z0-9_.]{0,79}$/.test(value) ? value : 'UNKNOWN_RULE';
const kinds = ['null','boolean','number','string','object','array'];
function typesFor(observation) {
  const result = {};
  for(const key of kinds) {
    const n = observation?.types?.[key];
    if(Number.isSafeInteger(n) && n > 0) result[key] = n;
  }
  return result;
}
function location(source, reference, {includeDetails}) {
  if(!includeDetails || !reference?.span) return undefined;
  const start = reference.span.start, end=reference.span.end;
  if(!Number.isSafeInteger(start)||!Number.isSafeInteger(end)||start<0||end<start||end>source.length)
    throw new RangeError('Evidence span does not belong to this document revision');
  const actual = source.slice(start, Math.min(end, start+160));
  return {start,end,pointer: reference.pointer === null ? null : slice(reference.pointer,256),
    rawExcerpt:actual,excerptTruncated:end-start>160};
}

export function buildEvidenceReport({findings,inspection,drift=null,source='',includeDetails=false}={}) {
  if(typeof source!=='string')throw new TypeError('Source must be a string');
  if(!Array.isArray(findings)||findings.length>MAX_FINDINGS)throw new RangeError('Findings exceed report budget');
  const result={
    formatVersion:REPORT_FORMAT_VERSION,
    privacyMode:includeDetails?'review-required':'redacted',
    description:'Local inspection of supplied JSON. Findings are potential risks, not proof of an API bug.',
    contents:'Findings were generated by enabled deterministic rules. Drift is an observation of supplied samples.',
    inspection:{total:count(inspection?.total),retained:findings.length,
      truncated:Boolean(inspection?.truncated)||count(inspection?.total)>findings.length,
      rules: Array.isArray(inspection?.rules) ? inspection.rules.slice(0,20).map(rule) : [],
      items:findings.map(x=>{
        const row={ruleId:rule(x.ruleId),severity:knownSeverity(x.severity),basis:'deterministic'};
        if(includeDetails) row.evidence=location(source,x.primary,{includeDetails});
        return row;
      })},
    schemaDrift:null,
    limitations:[
      'No finding means no issue detected under the enabled rules, not that the JSON is correct.',
      'Schema variations are observations in supplied samples, not validated contract violations.',
      'Findings and observations may be truncated by resource limits.'
    ]
  };
  if(drift) {
    if(!Array.isArray(drift.observations)||drift.observations.length>MAX_DRIFT)
      throw new RangeError('Schema observations exceed report budget');
    const r=drift.report;
    result.schemaDrift={
      mode:r?.mode==='multi_sample'?'multi_sample':'array',
      eligibleRecords:count(r?.eligibleRecords),excludedValues:count(r?.excludedValues),
      totalFields:count(r?.totalFields),totalObservations:count(r?.totalObservations),
      observedItems:drift.observations.length,
      truncated:Boolean(r?.observationsTruncated)||count(r?.totalObservations)>drift.observations.length,
      items:drift.observations.map(x=>{
        const row={ruleId:rule(x.ruleId),basis:'sample_observation',severity:'info',
          eligible:count(x.eligible),present:count(x.present),missing:count(x.missing),
          nullCount:count(x.nullCount),types:typesFor(x)};
        if(includeDetails) {
          row.field=slice(x.key,120);
          row.occurrence=count(x.occurrence);
          // Supplemental sample contents are intentionally *not* embedded in reports.
          row.sampleId=slice(x.primary?.sampleId,32) || null;
          row.pointer=x.primary?.pointer === null? null : slice(x.primary?.pointer,256);
        }
        return row;
      })
    };
  }
  if(includeDetails) result.disclosure='Detailed report: field names, pointers and raw primary-source excerpts may contain secrets. Review before copying or downloading; additional sample contents are not embedded.';
  else result.disclosure='Default privacy-first report: no source values, keys, filenames, pointers, raw excerpts or storage of inputs. Some aggregate counts may still reveal structural information.';
  return result;
}
const markdownEscape = text => String(text).replaceAll('\\','\\\\').replace(/([`*_<>\[\]|])/g,'\\$1').replaceAll('\r',' ').replaceAll('\n',' ');
export function serializeEvidenceReport(report,format='json') {
  if(!report || report.formatVersion!==REPORT_FORMAT_VERSION)throw new TypeError('Invalid report');
  if(format==='json')return JSON.stringify(report,null,2)+'\n';
  if(format!=='markdown')throw new RangeError('Unsupported report format');
  const lines=[
    '# JsonParseWeb local inspection report','',
    `- Mode: ${markdownEscape(report.privacyMode)}`,
    `- Findings: ${report.inspection.total} total (${report.inspection.retained} reported${report.inspection.truncated?', truncated':''})`,
    '- Findings are potential interoperability risks, not proof of an API bug.','',
    '## Findings',''
  ];
  for(const [i,item] of report.inspection.items.entries()) {
    lines.push(`${i+1}. ${markdownEscape(item.ruleId)} — ${markdownEscape(item.severity)}`);
    if(item.evidence) lines.push(`   - Evidence: ${markdownEscape(JSON.stringify(item.evidence))}`);
  }
  if(report.schemaDrift){
    const d=report.schemaDrift;
    lines.push('','## Schema observations','',
      `Eligible records: ${d.eligibleRecords}; total observations: ${d.totalObservations}${d.truncated?' (truncated)':''}.`);
    for(const x of d.items){
      lines.push(`- ${markdownEscape(x.ruleId)}: ${x.present}/${x.eligible} present; ${x.missing} missing; ${x.nullCount} null; ${markdownEscape(JSON.stringify(x.types))}`);
      if(x.field!==undefined) lines.push(`  - Field (reviewed export only): ${markdownEscape(JSON.stringify(x.field))}`);
    }
  }
  lines.push('','## Privacy and limitations','',markdownEscape(report.disclosure));
  for(const item of report.limitations)lines.push(`- ${markdownEscape(item)}`);
  return lines.join('\n')+'\n';
}
